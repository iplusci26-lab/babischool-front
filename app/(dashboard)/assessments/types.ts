/* ===========================================================
 * ASSESSMENT TYPES
 * =========================================================== */

export type AssessmentType =
  | "homework"
  | "test"
  | "exam"
  | "compo";


export type AssessmentStatus =
  | "draft"
  | "in_progress"
  | "ready"
  | "published"
  | "republish_required";


export type AssessmentCategory =
  | "class"
  | "scheduled";


/* ===========================================================
 * GROUPE DE CLASSE
 * =========================================================== */

export interface ClassroomGroup {

  id: string;

  name: string;

  display_order?: number;

  is_active?: boolean;

}


/* ===========================================================
 * ASSESSMENT
 * =========================================================== */

export interface Assessment {

  id: string;


  /* ---------------------------------------------------------
   * CLASSE
   * --------------------------------------------------------- */

  classroom: string;

  classroom_name: string;


  /* ---------------------------------------------------------
   * GROUPE
   *
   * null = toute la classe.
   * --------------------------------------------------------- */

  classroom_group?: string | null;

  classroom_group_name?: string | null;


  /* ---------------------------------------------------------
   * MATIÈRE
   * --------------------------------------------------------- */

  subject: string;

  subject_name: string;


  /* ---------------------------------------------------------
   * ENSEIGNANT
   * --------------------------------------------------------- */

  teacher: string;

  teacher_name: string;


  /* ---------------------------------------------------------
   * CRÉATEUR
   * --------------------------------------------------------- */

  created_by: string;

  created_by_name: string;


  /* ---------------------------------------------------------
   * PÉRIODE ACADÉMIQUE
   * --------------------------------------------------------- */

  term: string;

  term_name: string;


  /* ---------------------------------------------------------
   * TYPE
   * --------------------------------------------------------- */

  assessment_type: AssessmentType;


  /* ---------------------------------------------------------
   * NOTES
   * --------------------------------------------------------- */

  max_score: number;

  weight: number;


  /* ---------------------------------------------------------
   * DATE
   * --------------------------------------------------------- */

  date_assessment: string;


  /* ---------------------------------------------------------
   * STATUT
   * --------------------------------------------------------- */

  status: AssessmentStatus;

  status_label: string;


  /* ---------------------------------------------------------
   * PUBLICATION
   * --------------------------------------------------------- */

  can_publish: boolean;

  is_completed: boolean;


  /* ---------------------------------------------------------
   * DATES SYSTÈME
   * --------------------------------------------------------- */

  created_at: string;

  updated_at: string;


  /* ---------------------------------------------------------
   * STATISTIQUES
   * --------------------------------------------------------- */

  grades_count?: number;

  progress?: number;

  graded_students?: number;

  total_students?: number;


  /* ---------------------------------------------------------
   * CATÉGORIE
   * --------------------------------------------------------- */

  category: AssessmentCategory;

}


/* ===========================================================
 * CLASSE
 * =========================================================== */

export interface Classroom {

  id: string;

  name: string;


  /*
   * Groupes associés à la classe.
   *
   * Le tableau est optionnel car certaines réponses API
   * peuvent ne pas inclure les groupes.
   */

  groups?: ClassroomGroup[];

}


/* ===========================================================
 * MATIÈRE
 * =========================================================== */

export interface Subject {

  id: string;

  name: string;

  code?: string;

}


/* ===========================================================
 * PÉRIODE ACADÉMIQUE
 * =========================================================== */

export interface Term {

  id: string;

  name: string;

  term_type?: string;

  start_date?: string;

  end_date?: string;

  is_active?: boolean;

}


